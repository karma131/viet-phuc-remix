app.use((err,req,res,next)=>res.status(400).json({error:'Không thể xử lý dữ liệu gửi lên.'}));
app.listen(process.env.PORT||3001,'127.0.0.1',()=>console.log(`API và bản build: http://127.0.0.1:${process.env.PORT||3001}`));
